const {KeyboardCycle,cycleColor}=await import("./keyboard-cycle");
assert.deepEqual(cycleColor(0),[255,0,0]); assert.deepEqual(cycleColor(32),[0,255,0]); assert.deepEqual(cycleColor(64),[0,0,255]);
assert.deepEqual(cycleColor(96),cycleColor(0));
let scheduled:(()=>void)|undefined; let scheduledCount=0; let cancelled=0; let frames=0; let resolveFrame!:()=>void;
const fakeSchedule:any=(fn:()=>void)=>{scheduled=fn;scheduledCount++;return 1};
const fakeCancel:any=()=>{scheduled=undefined;cancelled++};
const cycle=new KeyboardCycle(async()=>{frames++;await new Promise<void>(r=>{resolveFrame=r})},()=>assert.fail("unexpected failure"),fakeSchedule,fakeCancel);
cycle.start(); scheduled!();
assert.equal(frames,1); assert.equal(scheduledCount,1,"No next frame until the current write completes");
cycle.stop(); resolveFrame(); await new Promise(r=>setImmediate(r));
assert.equal(scheduledCount,1,"Stop during an in-flight write prevents further frames");
let failures=0;
const failedCycle=new KeyboardCycle(async()=>{throw new Error("Disconnected")},()=>{failures++},fakeSchedule,fakeCancel);
failedCycle.start(); scheduled!(); await new Promise(r=>setImmediate(r));
assert.equal(failures,1,"Disconnected devices stop instead of being retried indefinitely");
console.log("App-driven cycling checks passed (RGB wheel, sequential frames, cancellation and failure).");
